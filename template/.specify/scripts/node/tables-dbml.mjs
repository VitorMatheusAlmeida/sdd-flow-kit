#!/usr/bin/env node
// Checks specs/<feature>/tabelas.planejado.dbml, the only output of speckit-tables: the tables of the feature as they
// will be, written by the agent from data-model.md, ready to paste into dbdiagram.io. The script never writes it.
//
//   node tables-dbml.mjs <feature-dir>   exits 1 when the file would not open in dbdiagram on its own:
//                                        a ref to a table or column the file does not define, a TableGroup member
//                                        that is not a table, a table or enum defined twice, or an enum of the
//                                        schema used without being defined in the file.
//
// It also lists, per table, how it differs from the current schema (sdd.config.json → tables.source, default
// dbml/schema.dbml, generated by Prisma): new, changed (+column, -column) or already equal (implemented).

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const fail = (message) => {
  console.error(message);
  process.exit(2);
};

const [featureDir] = process.argv.slice(2);
if (!featureDir) fail('usage: tables-dbml.mjs <feature-dir>');
const plannedFile = path.join(featureDir, 'tabelas.planejado.dbml');
if (!fs.existsSync(plannedFile)) fail(`missing ${plannedFile}: create it with /speckit-tables`);

const repoRoot = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim();
const configFile = path.join(repoRoot, 'sdd.config.json');
const config = fs.existsSync(configFile) ? JSON.parse(fs.readFileSync(configFile, 'utf8')) : {};
const sourceFile = path.join(repoRoot, config.tables?.source ?? 'dbml/schema.dbml');

// ───────────── reading DBML ─────────────

function parseDbml(raw) {
  const text = raw.replace(/\r\n/g, '\n'); // Windows checkouts (core.autocrlf=true) bring CRLF
  const tables = [];
  const enums = [];
  const groups = [];
  const refs = [];
  const blockPattern = /^(Table|Enum|TableGroup)\s+"?([\w.]+)"?(\s*\[[^\]]*\])?\s*\{\n([\s\S]*?)^\}/gm;
  let match;
  while ((match = blockPattern.exec(text))) {
    const block = { name: match[2], body: match[4] };
    if (match[1] === 'Table') tables.push({ ...block, columns: columnsOf(block.body) });
    else if (match[1] === 'Enum') enums.push(block);
    else groups.push({ ...block, members: block.body.split('\n').map((line) => line.trim().replace(/"/g, '')).filter(Boolean) });
  }
  for (const line of text.split('\n')) {
    const ref = line.trim().match(/^Ref\b[^:]*:\s*"?(\w+)"?\."?(\w+)"?\s*[<>-]+\s*"?(\w+)"?\."?(\w+)"?/);
    if (ref) refs.push({ where: line.trim(), targets: [[ref[1], ref[2]], [ref[3], ref[4]]] });
  }
  for (const table of tables) {
    for (const column of table.columns) {
      for (const inline of column.line.matchAll(/ref:\s*[<>-]+\s*"?(\w+)"?\."?(\w+)"?/g)) {
        refs.push({ where: `${table.name}.${column.name}`, targets: [[inline[1], inline[2]]] });
      }
    }
  }
  return { tables, enums, groups, refs };
}

function columnsOf(body) {
  const columns = [];
  let nested = 0;
  for (const line of body.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed) continue;
    if (/^(indexes|Note)\b.*\{$/.test(trimmed)) {
      nested++;
      continue;
    }
    if (nested) {
      if (trimmed === '}') nested--;
      continue;
    }
    if (/^Note\s*:/.test(trimmed)) continue;
    const column = trimmed.match(/^"?(\w+)"?\s+"?([\w.]+)/);
    if (column) columns.push({ name: column[1], type: column[2], line: trimmed });
  }
  return columns;
}

const planned = parseDbml(fs.readFileSync(plannedFile, 'utf8'));
const source = fs.existsSync(sourceFile) ? parseDbml(fs.readFileSync(sourceFile, 'utf8')) : null;
if (!source) console.warn(`warning: ${sourceFile} not found (run "npx prisma generate"); no comparison with the schema`);

// ───────────── checks ─────────────

const errors = [];
const tableByName = new Map(planned.tables.map((table) => [table.name, table]));
const enumNames = new Set(planned.enums.map((item) => item.name));
for (const [kind, list] of [['Table', planned.tables], ['Enum', planned.enums]]) {
  const seen = new Set();
  for (const { name } of list) {
    if (seen.has(name)) errors.push(`${kind} "${name}" is defined twice`);
    seen.add(name);
  }
}
for (const ref of planned.refs) {
  for (const [table, column] of ref.targets) {
    if (!tableByName.has(table)) errors.push(`${ref.where}: ref to "${table}", which the file does not define`);
    else if (!tableByName.get(table).columns.some((item) => item.name === column)) errors.push(`${ref.where}: ref to "${table}.${column}", which does not exist`);
  }
}
for (const group of planned.groups) {
  for (const member of group.members) if (!tableByName.has(member)) errors.push(`TableGroup "${group.name}": "${member}" is not a table of the file`);
}
const sourceEnums = new Set(source?.enums.map((item) => item.name) ?? []);
for (const table of planned.tables) {
  for (const column of table.columns) {
    if (sourceEnums.has(column.type) && !enumNames.has(column.type)) errors.push(`${table.name}.${column.name}: enum "${column.type}" is used but not defined in the file`);
  }
}

// ───────────── report ─────────────

const sourceTables = new Map(source?.tables.map((table) => [table.name, table]) ?? []);
const sourceTableNames = new Set(sourceTables.keys());
for (const table of planned.tables) {
  const current = sourceTables.get(table.name);
  if (!current) {
    console.log(`${table.name}: new`);
    continue;
  }
  // Prisma relation fields (a column whose type is a table) are not columns of the database.
  const real = (columns) => columns.filter((column) => !sourceTableNames.has(column.type) || sourceEnums.has(column.type)).map((column) => column.name);
  const now = new Set(real(current.columns));
  const next = new Set(real(table.columns));
  const changes = [...[...next].filter((name) => !now.has(name)).map((name) => `+${name}`), ...[...now].filter((name) => !next.has(name)).map((name) => `-${name}`)];
  console.log(`${table.name}: ${changes.length ? `changes ${changes.join(', ')}` : 'same columns as the schema (implemented, or only a reference)'}`);
}

if (errors.length) {
  console.error(`\n${errors.length} error(s) — the file would not open on its own in dbdiagram:`);
  for (const error of errors) console.error(`- ${error}`);
  process.exit(1);
}
console.log(`\nok: ${planned.tables.length} table(s), ${planned.enums.length} enum(s), ${planned.refs.length} ref(s); paste ${path.basename(plannedFile)} into dbdiagram.io`);
